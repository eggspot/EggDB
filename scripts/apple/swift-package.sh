#!/usr/bin/env bash
set -euo pipefail

usage="usage: scripts/apple/swift-package.sh <tag> <xcframework zip> <output directory>

Writes the Swift package a release publishes (D1093): <output directory> gets a Package.swift
whose CEggDB binary target is the release's XCFramework zip, downloaded from the release by URL
and checked by its checksum, and the EggDB Swift sources, so an app adds
.package(url: \"https://github.com/eggspot/EggDB\", branch: \"swift-package\") or pins a revision.
Needs swift for the checksum."

[ $# -eq 3 ] || { echo "$usage" >&2; exit 2; }
tag=$1
zip=$2
out=$3
root=$(cd "$(dirname "$0")/../.." && pwd)
checksum=$(swift package compute-checksum "$zip")
name=$(basename "$zip")
mkdir -p "$out/Sources"
rm -rf "$out/Sources/EggDB"
cp -R "$root/drivers/swift/Sources/EggDB" "$out/Sources/EggDB"
cat > "$out/Package.swift" <<MANIFEST
// swift-tools-version:5.9
import PackageDescription

let package = Package(
    name: "EggDB",
    platforms: [.macOS(.v11), .iOS(.v13)],
    products: [.library(name: "EggDB", targets: ["EggDB"])],
    targets: [
        .binaryTarget(
            name: "CEggDB",
            url: "https://github.com/eggspot/EggDB/releases/download/$tag/$name",
            checksum: "$checksum"
        ),
        .target(name: "EggDB", dependencies: ["CEggDB"], path: "Sources/EggDB"),
    ]
)
MANIFEST
printf 'EggDB %s for Swift: generated by the release workflow from drivers/swift; see https://github.com/eggspot/EggDB/blob/%s/docs/c-api.md\n' "$tag" "$tag" > "$out/README.md"
echo "wrote $out/Package.swift for $tag ($checksum)"
