SELECT id, row_number() OVER w, rank() OVER w, dense_rank() OVER w, percent_rank() OVER w, cume_dist() OVER w, ntile(2) OVER w FROM w_sales WINDOW w AS (PARTITION BY region ORDER BY amount) ORDER BY id;
SELECT id, amount, sum(amount) OVER (PARTITION BY region ORDER BY id) AS running, sum(amount) OVER (PARTITION BY region) AS total, count(*) OVER (PARTITION BY region) AS rows_in, max(amount) OVER (ORDER BY id ROWS 2 PRECEDING) AS recent_max FROM w_sales ORDER BY id;
SELECT id, lag(amount) OVER w AS prev, lead(amount, 2, -1) OVER w AS next2, first_value(amount) OVER w AS first, last_value(amount) OVER w AS last, nth_value(amount, 2) OVER w AS second FROM w_sales WINDOW w AS (PARTITION BY region ORDER BY id ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) ORDER BY id;
SELECT id, sum(amount) OVER (ORDER BY id ROWS BETWEEN 1 PRECEDING AND 1 FOLLOWING) AS s3, count(*) OVER (ORDER BY amount RANGE BETWEEN 10 PRECEDING AND CURRENT ROW) AS near, count(*) OVER (ORDER BY amount GROUPS BETWEEN 1 PRECEDING AND 1 FOLLOWING) AS g, sum(amount) OVER (ORDER BY id ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING EXCLUDE CURRENT ROW) AS others FROM w_sales ORDER BY id;
SELECT id, amount * 100 / sum(amount) OVER (PARTITION BY region) AS share FROM w_sales WHERE amount IS NOT NULL ORDER BY rank() OVER (ORDER BY amount DESC), id;
SELECT id, sum(amount) OVER (w ORDER BY id) FROM w_sales WINDOW w AS (PARTITION BY region) ORDER BY id;
SELECT region, string_agg(id::text, ',') OVER (PARTITION BY region ORDER BY id) AS ids FROM w_sales ORDER BY id;
SELECT region, count(*) FILTER (WHERE amount > 15) AS big, percentile_disc(0.5) WITHIN GROUP (ORDER BY amount) AS median, percentile_cont(0.5) WITHIN GROUP (ORDER BY amount) AS middle, mode() WITHIN GROUP (ORDER BY amount) AS common FROM w_sales GROUP BY region ORDER BY region;
SELECT s.id, x.n FROM w_sales s, LATERAL (SELECT count(*) AS n FROM w_sales t WHERE t.region = s.region AND t.id < s.id) x ORDER BY s.id;
SELECT s.id, g FROM w_sales s CROSS JOIN LATERAL generate_series(1, s.id % 3) AS g ORDER BY 1, 2;
