#!/usr/bin/env bash
set -euo pipefail

usage="usage: scripts/pg-follow/check.sh <eggdb binary> <work directory>

Starts PostgreSQL 17 in Docker with wal_level=logical, fills a database, and follows it with
eggdb follow while writes keep arriving: inserts, updates, deletes and a truncate, during the
copy and after it. Then it stops the follow with SIGTERM and compares every table and sequence
value in EggDB with PostgreSQL. It resumes that follow after columns were added while it was
stopped, drops and adds columns, creates a table and runs large streamed transactions (one with a
rolled-back savepoint, one aborted) while it follows, cuts its connection and checks it reconnects,
then resumes it once more with --until caught-up, which drops its slot. A last run uses
--until caught-up from the start. Fails on the first difference. PSQL names the psql command
(default: psql inside the container)."

[ $# -eq 2 ] || { echo "$usage" >&2; exit 2; }
eggdb=$(cd "$(dirname "$1")" && pwd)/$(basename "$1")
work=$2
mkdir -p "$work"
work=$(cd "$work" && pwd)
container="eggdb-pg-follow"
port=55432
export PGPASSWORD=follow-check

fail() {
  echo "pg-follow check FAILED: $*" >&2
  [ -f "$work/follow.err" ] && sed 's/^/  follow: /' "$work/follow.err" >&2
  exit 1
}

cleanup() {
  [ -n "${follow_pid:-}" ] && kill -TERM "$follow_pid" 2> /dev/null || true
  docker rm -f "$container" > /dev/null 2>&1 || true
}
trap cleanup EXIT

docker rm -f "$container" > /dev/null 2>&1 || true
docker run -d --name "$container" -e POSTGRES_PASSWORD="$PGPASSWORD" -p "$port:5432" postgres:17 \
  -c wal_level=logical -c max_replication_slots=4 -c max_wal_senders=4 -c logical_decoding_work_mem=64kB > /dev/null
psql() {
  docker exec -i -e PGPASSWORD "$container" psql -U postgres -d app -X -q -A -t -v ON_ERROR_STOP=1 "$@"
}
for _ in $(seq 1 60); do
  docker exec "$container" pg_isready -U postgres > /dev/null 2>&1 && break
  sleep 1
done
docker exec -i "$container" psql -U postgres -X -q -c "CREATE DATABASE app" || fail "cannot create the database"
psql <<'SQL'
CREATE TABLE customers (id serial PRIMARY KEY, name text NOT NULL, email text UNIQUE, created date DEFAULT CURRENT_DATE);
CREATE TABLE orders (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id int REFERENCES customers (id), amount numeric(10,2) NOT NULL, note text);
CREATE TABLE events (at timestamptz NOT NULL, payload jsonb) ;
ALTER TABLE events REPLICA IDENTITY FULL;
CREATE INDEX orders_by_customer ON orders (customer_id);
CREATE TABLE notes (id int PRIMARY KEY, body text, extra text);
INSERT INTO notes VALUES (1, 'one', 'x'), (2, 'two', NULL), (3, 'three', 'y');
INSERT INTO customers (name, email) SELECT 'customer ' || i, 'c' || i || '@example.com' FROM generate_series(1, 2000) i;
INSERT INTO orders (customer_id, amount, note) SELECT 1 + i % 2000, (i % 997) / 7.0, CASE WHEN i % 3 = 0 THEN NULL ELSE 'it''s order ' || i END FROM generate_series(1, 20000) i;
INSERT INTO events SELECT timestamptz '2026-01-01 00:00:00+00' + i * interval '1 minute', jsonb_build_object('n', i) FROM generate_series(1, 500) i;
SQL

writes() {
  psql <<'SQL'
INSERT INTO customers (name, email) VALUES ('late arrival', 'late@example.com');
UPDATE orders SET amount = amount + 1, note = 'changed' WHERE id % 50 = 0;
DELETE FROM orders WHERE id % 97 = 0;
BEGIN;
INSERT INTO orders (customer_id, amount) SELECT 7, 12.34 FROM generate_series(1, 300);
UPDATE customers SET email = NULL WHERE id = 3;
COMMIT;
DELETE FROM events WHERE (payload->>'n')::int % 10 = 0;
TRUNCATE events;
INSERT INTO events VALUES ('2026-02-02 02:02:02+00', '{"after": "truncate"}');
SQL
}

compare() {
  local file=$1
  shift
  EGGDB_PASSWORD=served "$eggdb" serve "$file" --listen 127.0.0.1:0 --database app --format json > "$work/serve.out" 2> "$work/serve.err" &
  local serve_pid=$!
  for _ in $(seq 1 100); do
    [ -s "$work/serve.out" ] && break
    sleep 0.1
  done
  local served_port
  served_port=$(sed -E 's/.*"port":([0-9]+).*/\1/' "$work/serve.out" | head -n 1)
  for query in \
    "SELECT id, name, coalesce(email, '<null>'), created FROM customers ORDER BY id" \
    "SELECT id, customer_id, amount, coalesce(note, '<null>') FROM orders ORDER BY id" \
    "SELECT at, payload::text FROM events ORDER BY at" \
    "SELECT * FROM notes ORDER BY id" \
    "$@" \
    "SELECT nextval('customers_id_seq')"; do
    psql -c "$query" > "$work/source.out"
    docker run --rm -i --network host -e PGPASSWORD=served postgres:17 \
      psql "host=127.0.0.1 port=$served_port user=eggdb dbname=app" -X -q -A -t -c "$query" > "$work/target.out" 2> "$work/eggdb.err" \
      || { kill -TERM "$serve_pid"; fail "querying eggdb failed: $(cat "$work/eggdb.err")"; }
    diff -u "$work/source.out" "$work/target.out" > "$work/output.diff" || { kill -TERM "$serve_pid"; fail "$query differs (see output.diff)"; }
  done
  kill -TERM "$serve_pid"
  wait "$serve_pid" || true
}

url="postgres://postgres@127.0.0.1:$port/app?sslmode=disable"
rm -f "$work/follow.db"
"$eggdb" follow --create "$work/follow.db" "$url" --format json > "$work/follow.out" 2> "$work/follow.err" &
follow_pid=$!
for _ in $(seq 1 120); do
  grep -q '"event":"slot"' "$work/follow.out" 2> /dev/null && break
  sleep 0.5
done
writes
for _ in $(seq 1 120); do
  grep -q '"event":"copied"' "$work/follow.out" 2> /dev/null && break
  sleep 0.5
done
grep -q '"event":"copied"' "$work/follow.out" || fail "the copy did not finish"
psql -c "INSERT INTO customers (name) VALUES ('after the copy'); UPDATE customers SET name = 'renamed' WHERE id = 1"
sleep 3
kill -TERM "$follow_pid"
wait "$follow_pid" || fail "follow did not exit 0 after SIGTERM"
follow_pid=
grep -q '"event":"stopped","ok":true' "$work/follow.out" || fail "no stopped event: $(tail -n 3 "$work/follow.out")"
grep -q '"slot_dropped":false' "$work/follow.out" || fail "the slot was not kept for resuming"
compare "$work/follow.db"

psql <<'SQL'
ALTER TABLE orders ADD COLUMN priority int DEFAULT 1;
UPDATE orders SET priority = 5 WHERE id <= 10;
INSERT INTO customers (name) VALUES ('while stopped');
SQL
"$eggdb" follow "$work/follow.db" "$url" --format json > "$work/resume.out" 2> "$work/follow.err" &
follow_pid=$!
for _ in $(seq 1 60); do
  grep -q '"event":"resumed"' "$work/resume.out" 2> /dev/null && break
  sleep 0.5
done
grep -q '"event":"resumed"' "$work/resume.out" || fail "the follow did not resume: $(cat "$work/resume.out")"
grep -q '"event":"copied"' "$work/resume.out" && fail "the resumed follow copied the tables again"
psql <<'SQL'
ALTER TABLE notes DROP COLUMN extra;
INSERT INTO notes VALUES (4, 'four');
ALTER TABLE customers ADD COLUMN tier text;
UPDATE customers SET tier = 'gold' WHERE id <= 5;
CREATE TABLE late_arrivals (id int PRIMARY KEY, label text, customer_id int REFERENCES customers (id));
INSERT INTO late_arrivals SELECT i, 'row ' || i, 1 + i % 5 FROM generate_series(1, 50) i;
BEGIN;
INSERT INTO notes SELECT i, repeat('streamed ', 40) FROM generate_series(100, 3099) i;
SAVEPOINT half;
INSERT INTO notes SELECT i, 'rolled back' FROM generate_series(5000, 5999) i;
ROLLBACK TO SAVEPOINT half;
UPDATE late_arrivals SET label = 'in a streamed transaction' WHERE id = 1;
COMMIT;
BEGIN;
INSERT INTO notes SELECT i, repeat('aborted ', 40) FROM generate_series(7000, 9999) i;
ROLLBACK;
SQL
for _ in $(seq 1 60); do
  grep -q '"event":"table_added"' "$work/resume.out" 2> /dev/null && break
  sleep 0.5
done
grep -q '"event":"table_added","table":"public.late_arrivals","copied":true' "$work/resume.out" \
  || fail "the table created during the follow was not added: $(cat "$work/resume.out")"
grep -q '"event":"stream","protocol":2,"streaming":true' "$work/resume.out" \
  || fail "the follow did not ask for streamed transactions: $(cat "$work/resume.out")"
for _ in $(seq 1 60); do
  [ "$(grep -c '"event":"schema_changed"' "$work/resume.out" 2> /dev/null)" -ge 3 ] && break
  sleep 0.5
done
[ "$(grep -c '"event":"schema_changed"' "$work/resume.out")" -ge 3 ] || fail "the column changes were not applied: $(cat "$work/resume.out")"
psql -c "SELECT pg_terminate_backend(pid) FROM pg_stat_replication" > /dev/null
psql -c "INSERT INTO customers (name, tier) VALUES ('after the reconnect', 'silver')"
for _ in $(seq 1 120); do
  grep -q '"event":"reconnected"' "$work/resume.out" 2> /dev/null && break
  sleep 0.5
done
grep -q '"event":"reconnecting"' "$work/resume.out" || fail "no reconnecting event after the connection was cut"
grep -q '"event":"reconnected"' "$work/resume.out" || fail "the follow did not reconnect: $(tail -n 3 "$work/resume.out")"
sleep 3
kill -TERM "$follow_pid"
wait "$follow_pid" || fail "the resumed follow did not exit 0 after SIGTERM"
follow_pid=
"$eggdb" follow "$work/follow.db" "$url" --until caught-up --format json > "$work/resume-caught-up.out" 2> "$work/follow.err" \
  || fail "resuming with --until caught-up failed"
grep -q '"slot_dropped":true' "$work/resume-caught-up.out" || fail "the finished follow kept its slot"
compare "$work/follow.db" \
  "SELECT id, coalesce(priority, -1) FROM orders ORDER BY id" \
  "SELECT id, coalesce(tier, '<null>') FROM customers ORDER BY id" \
  "SELECT * FROM late_arrivals ORDER BY id"

rm -f "$work/caught-up.db"
"$eggdb" follow --create "$work/caught-up.db" "$url" --until caught-up --format json > "$work/caught-up.out" 2> "$work/follow.err" \
  || fail "follow --until caught-up failed"
grep -q '"reason":"caught_up"' "$work/caught-up.out" || fail "no caught_up stop"
compare "$work/caught-up.db"
docker exec -i "$container" psql -U postgres -d app -X -q -A -t -c "SELECT count(*) FROM pg_replication_slots" > "$work/slots.out"
[ "$(cat "$work/slots.out")" = "0" ] || fail "a replication slot was left behind"
echo "pg-follow check passed: copy, live changes (insert, update, delete, truncate), sequences, SIGTERM, resuming, column changes, a table created during the follow, streamed and aborted transactions, reconnecting and --until caught-up"
