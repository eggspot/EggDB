CREATE INDEX orders_customer_idx ON public.orders (customer_id);
CREATE INDEX orders_placed_idx ON public.orders (ordered_on DESC, status);
CREATE INDEX events_happened_idx ON public.events (happened);
CREATE UNIQUE INDEX ledger_account_invoice_idx ON public.ledger (account, invoice);
CREATE INDEX log_lines_level_idx ON public.log_lines USING hash (level);
CREATE INDEX stock_product_idx ON shop.stock (product_id);

CREATE VIEW public.order_totals AS
SELECT c.id AS customer_id, c.name, count(o.id) AS orders, sum(o.total) AS total
FROM public.customers c
JOIN public.orders o ON o.customer_id = c.id
GROUP BY c.id, c.name;

CREATE VIEW shop.stock_by_product AS
SELECT p.sku, p.title, s.warehouse, s.on_hand
FROM shop.stock s
JOIN public.products p ON p.id = s.product_id
WHERE s.on_hand > 0;

CREATE VIEW public.active_customers AS
SELECT id, name, email FROM public.customers WHERE active;
COMMENT ON VIEW public.active_customers IS 'customers who can order';

CREATE FUNCTION public.touch_note() RETURNS trigger LANGUAGE plpgsql AS $body$
BEGIN
    NEW.note := coalesce(NEW.note, '') || ';';
    RETURN NEW;
END;
$body$;

CREATE TRIGGER customers_touch BEFORE UPDATE ON public.customers
FOR EACH ROW EXECUTE FUNCTION public.touch_note();

CREATE MATERIALIZED VIEW public.daily_orders AS
SELECT ordered_on, count(*) AS orders FROM public.orders GROUP BY ordered_on;

