//! The protocol examples of [MS-TDS] section 4, read by EggDB's parsers: the PRELOGIN request
//! of 4.1 (a SQL Server 2005 client asking for encryption and MARS) and the LOGIN7 request of
//! 4.2 (a TDS 7.2 client logging in as `sa` with an empty password). Both must parse to the
//! fields the specification annotates, and EggDB, which speaks TDS 7.4 without encryption,
//! must refuse both clients.

mod common;

