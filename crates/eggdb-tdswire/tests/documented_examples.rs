#[test]
fn the_prelogin_example_parses_to_its_annotated_fields() {
    assert_eq!(usize::from(PRELOGIN_REQUEST[3]), PRELOGIN_REQUEST.len());
    let prelogin = parse_prelogin(&PRELOGIN_REQUEST[8..]).unwrap();
    assert_eq!(prelogin.version, [9, 0, 0, 0, 0, 0]);
    assert_eq!(prelogin.encryption, Some(ENCRYPT_ON));
    assert_eq!(prelogin.instance, vec![0]);
    assert!(prelogin.mars);
    assert!(prelogin.wants_encryption());
    assert!(!prelogin.names_another_instance());
}

#[test]
fn the_login_example_parses_to_its_annotated_fields() {
    assert_eq!(usize::from(LOGIN_REQUEST[3]), LOGIN_REQUEST.len());
    let login = parse_login7(&LOGIN_REQUEST[8..]).unwrap();
    assert_eq!(login.tds_version, 0x7209_0002);
    assert_eq!(login.packet_size, 4096);
    assert_eq!(login.host_name, "skostov1");
    assert_eq!(login.user_name, "sa");
    assert_eq!(
        login.password.as_ref().map(|password| password.bytes()),
        Some(&[][..])
    );
    assert_eq!(login.app_name, "OSQL-32");
    assert_eq!(login.database, "");
    assert!(login.odbc_defaults);
    assert!(!login.integrated_security);
}

#[test]
fn eggdb_refuses_both_example_clients() {
    let server = TestServer::start(4);
    let mut encrypting = Client::connect(server.address);
    encrypting.send_raw(&PRELOGIN_REQUEST);
    let (kind, _) = encrypting.read_message().unwrap();
    assert_eq!(kind, 0x04);
    assert!(encrypting.is_closed());
    let mut old = Client::connect(server.address);
    old.prelogin(0x02).unwrap();
    old.send_raw(&LOGIN_REQUEST);
    let (_, reply) = old.read_message().unwrap();
    assert_eq!(errors(&parse_tokens(&reply))[0].0, 18456);
    assert!(
        server
            .log()
            .iter()
            .any(|line| line.contains("EggDB needs TDS 7.4"))
    );
}
