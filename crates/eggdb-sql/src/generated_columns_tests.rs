use crate::memory_store::MemoryStore;
use crate::tests::render;
use crate::{Dialect, Session, SqlError};

fn run(session: &mut Session<'_>, sql: &str) -> Result<Vec<String>, SqlError> {
    let mut outputs = Vec::new();
    session.execute(sql, &mut |result| outputs.push(render(&result)))?;
    Ok(outputs)
}

fn last(session: &mut Session<'_>, sql: &str) -> String {
    match run(session, sql) {
        Ok(outputs) => outputs.last().cloned().unwrap_or_default(),
        Err(error) => panic!("{sql}: {error}"),
    }
}

fn fails(session: &mut Session<'_>, sql: &str) -> SqlError {
    match run(session, sql) {
        Ok(outputs) => panic!("{sql} succeeded: {outputs:?}"),
        Err(error) => error,
    }
}

#[test]
fn the_postgresql_manual_people_table_computes_height_in_on_insert_and_update() {
    let store = MemoryStore::default();
    let mut session = Session::new(&store);
    last(
        &mut session,
        "CREATE TABLE people (height_cm numeric, \
         height_in numeric GENERATED ALWAYS AS (height_cm / 2.54) STORED)",
    );
    last(&mut session, "INSERT INTO people (height_cm) VALUES (254)");
    assert_eq!(
        last(
            &mut session,
            "SELECT CASE WHEN height_in = 100 THEN 'yes' ELSE 'no' END AS exact FROM people"
        ),
        "exact\nyes\nSELECT 1"
    );
    last(&mut session, "UPDATE people SET height_cm = 508");
    assert_eq!(
        last(
            &mut session,
            "SELECT CASE WHEN height_in = 200 THEN 'yes' ELSE 'no' END AS exact FROM people"
        ),
        "exact\nyes\nSELECT 1"
    );
    let error = fails(
        &mut session,
        "INSERT INTO people (height_cm, height_in) VALUES (1, 2)",
    );
    assert_eq!(error.state().code(), "428C9");
    assert_eq!(
        error.message(),
        "cannot insert a non-DEFAULT value into column \"height_in\""
    );
    assert_eq!(
        error.detail(),
        Some("Column \"height_in\" is a generated column.")
    );
    let error = fails(&mut session, "UPDATE people SET height_in = 3");
    assert_eq!(
        error.message(),
        "column \"height_in\" can only be updated to DEFAULT"
    );
    last(
        &mut session,
        "INSERT INTO people (height_cm, height_in) VALUES (2.54, DEFAULT)",
    );
    assert_eq!(
        last(
            &mut session,
            "SELECT count(*) FROM people WHERE height_in = 1"
        ),
        "count\n1\nSELECT 1"
    );
    let error = fails(
        &mut session,
        "INSERT INTO people (height_cm, height_in) SELECT 1, 2",
    );
    assert_eq!(error.state().code(), "428C9");
}

#[test]
fn postgresql_refuses_the_expressions_its_manual_rules_out() {
    let store = MemoryStore::default();
    let mut session = Session::new(&store);
    for (sql, state) in [
        (
            "CREATE TABLE t (a int, b int GENERATED ALWAYS AS (a + 1) STORED, \
             c int GENERATED ALWAYS AS (b * 2) STORED)",
            "42P17",
        ),
        (
            "CREATE TABLE t (a int, b int GENERATED ALWAYS AS (b + 1) STORED)",
            "42P17",
        ),
        (
            "CREATE TABLE t (a float8, b float8 GENERATED ALWAYS AS (random()) STORED)",
            "42P17",
        ),
        (
            "CREATE TABLE t (a int, b int GENERATED ALWAYS AS ((SELECT 1)) STORED)",
            "0A000",
        ),
        (
            "CREATE TABLE t (a int, b int GENERATED ALWAYS AS (count(a)) STORED)",
            "42803",
        ),
        (
            "CREATE TABLE t (a int, b int GENERATED BY DEFAULT AS (a) STORED)",
            "42601",
        ),
        (
            "CREATE TABLE t (a int, b int DEFAULT 1 GENERATED ALWAYS AS (a) STORED)",
            "42601",
        ),
        (
            "CREATE TABLE t (a int, b int GENERATED ALWAYS AS (missing + 1) STORED)",
            "42703",
        ),
    ] {
        assert_eq!(fails(&mut session, sql).state().code(), state, "{sql}");
    }
    let error = fails(
        &mut session,
        "CREATE TABLE t (a float8, b float8 GENERATED ALWAYS AS (random()) STORED)",
    );
    assert_eq!(error.message(), "generation expression is not immutable");
}

#[test]
fn postgresql_catalogs_describe_stored_and_virtual_generated_columns() {
    let store = MemoryStore::default();
    let mut session = Session::new(&store);
    last(
        &mut session,
        "CREATE TABLE t (a int, s int GENERATED ALWAYS AS (a * 2) STORED, \
         v int GENERATED ALWAYS AS (a * 3))",
    );
    assert_eq!(
        last(
            &mut session,
            "SELECT attname, attgenerated, atthasdef FROM pg_attribute \
             WHERE attrelid = 't'::regclass AND attnum > 0 ORDER BY attnum"
        ),
        "attname|attgenerated|atthasdef\na||f\ns|s|t\nv|v|t\nSELECT 3"
    );
    assert_eq!(
        last(
            &mut session,
            "SELECT column_name, is_generated, generation_expression, column_default \
             FROM information_schema.columns WHERE table_name = 't' ORDER BY ordinal_position"
        ),
        "column_name|is_generated|generation_expression|column_default\n\
         a|NEVER|NULL|NULL\ns|ALWAYS|a * 2|NULL\nv|ALWAYS|a * 3|NULL\nSELECT 3"
    );
    assert_eq!(
        last(
            &mut session,
            "SELECT count(*) FROM pg_attrdef WHERE adrelid = 't'::regclass"
        ),
        "count\n2\nSELECT 1"
    );
    last(&mut session, "INSERT INTO t (a) VALUES (5)");
    assert_eq!(
        last(&mut session, "SELECT a, s, v FROM t"),
        "a|s|v\n5|10|15\nSELECT 1"
    );
    last(&mut session, "CREATE INDEX t_s ON t (s)");
    assert_eq!(
        fails(&mut session, "CREATE INDEX t_v ON t (v)")
            .state()
            .code(),
        "0A000"
    );
}

#[test]
fn postgresql_add_column_computes_existing_rows_and_drop_column_follows_dependencies() {
    let store = MemoryStore::default();
    let mut session = Session::new(&store);
    last(&mut session, "CREATE TABLE t (id int PRIMARY KEY, a int)");
    last(&mut session, "INSERT INTO t VALUES (1, 10), (2, 20)");
    last(
        &mut session,
        "ALTER TABLE t ADD COLUMN b int GENERATED ALWAYS AS (a + 1) STORED",
    );
    assert_eq!(
        last(&mut session, "SELECT id, b FROM t ORDER BY id"),
        "id|b\n1|11\n2|21\nSELECT 2"
    );
    last(&mut session, "ALTER TABLE t RENAME COLUMN a TO amount");
    last(&mut session, "INSERT INTO t (id, amount) VALUES (3, 30)");
    assert_eq!(
        last(&mut session, "SELECT b FROM t WHERE id = 3"),
        "b\n31\nSELECT 1"
    );
    let error = fails(&mut session, "ALTER TABLE t DROP COLUMN amount");
    assert_eq!(error.state().code(), "2BP01");
    assert_eq!(
        error.message(),
        "cannot drop column amount of table t because other objects depend on it"
    );
    last(&mut session, "ALTER TABLE t DROP COLUMN amount CASCADE");
    assert_eq!(
        last(&mut session, "SELECT * FROM t ORDER BY id"),
        "id\n1\n2\n3\nSELECT 3"
    );
}

#[test]
fn the_mysql_manual_triangle_computes_its_virtual_squared_hypotenuse() {
    let store = MemoryStore::default();
    let mut session = Session::with_dialect(&store, Dialect::MySql);
    last(
        &mut session,
        "CREATE TABLE triangle (sidea DOUBLE, sideb DOUBLE, \
         sidec DOUBLE AS (sidea * sidea + sideb * sideb))",
    );
    last(
        &mut session,
        "INSERT INTO triangle (sidea, sideb) VALUES (1, 1), (3, 4), (6, 8)",
    );
    assert_eq!(
        last(
            &mut session,
            "SELECT CASE WHEN sidec = 25 THEN 'yes' ELSE 'no' END AS right_angle \
             FROM triangle WHERE sidea = 3"
        ),
        "right_angle\nyes\nSELECT 1"
    );
    let error = fails(
        &mut session,
        "INSERT INTO triangle (sidea, sideb, sidec) VALUES (1, 1, 1)",
    );
    assert_eq!(error.vendor_code(), Some(3105));
    assert_eq!(
        error.message(),
        "The value specified for generated column 'sidec' in table 'triangle' is not allowed."
    );
    last(&mut session, "INSERT INTO triangle VALUES (5, 12, DEFAULT)");
    assert_eq!(
        last(
            &mut session,
            "SELECT CASE WHEN sidec = 169 THEN 'yes' ELSE 'no' END AS right_angle \
             FROM triangle WHERE sidea = 5"
        ),
        "right_angle\nyes\nSELECT 1"
    );
    assert_eq!(
        last(&mut session, "SHOW COLUMNS FROM triangle LIKE 'sidec'"),
        "Field|Type|Null|Key|Default|Extra\nsidec|double|YES||NULL|VIRTUAL GENERATED\nSELECT 1"
    );
}

#[test]
fn mysql_stored_columns_show_in_information_schema_and_guard_their_order() {
    let store = MemoryStore::default();
    let mut session = Session::with_dialect(&store, Dialect::MySql);
    last(
        &mut session,
        "CREATE TABLE t (a INT, b INT GENERATED ALWAYS AS (a * 2) STORED, c INT AS (b + 1))",
    );
    assert_eq!(
        last(
            &mut session,
            "SELECT column_name AS name, extra AS kind FROM information_schema.columns \
             WHERE table_name = 't' ORDER BY ordinal_position"
        ),
        "name|kind\na|\nb|STORED GENERATED\nc|VIRTUAL GENERATED\nSELECT 3"
    );
    last(&mut session, "INSERT INTO t (a) VALUES (4)");
    assert_eq!(
        last(&mut session, "SELECT b, c FROM t"),
        "b|c\n8|9\nSELECT 1"
    );
    let error = fails(
        &mut session,
        "CREATE TABLE u (a INT, b INT AS (c + 1), c INT AS (a + 1))",
    );
    assert_eq!(error.vendor_code(), Some(3107));
    let error = fails(&mut session, "ALTER TABLE t DROP COLUMN a");
    assert_eq!(error.vendor_code(), Some(3108));
    let error = fails(&mut session, "CREATE TABLE u (a INT, b DOUBLE AS (RAND()))");
    assert_eq!(error.vendor_code(), Some(3763));
}

#[test]
fn the_sqlite_manual_t1_table_keeps_generated_columns_out_of_inserts() {
    let store = MemoryStore::default();
    let mut session = Session::with_dialect(&store, Dialect::Sqlite);
    last(
        &mut session,
        "CREATE TABLE t1(a INTEGER PRIMARY KEY, b INT, c TEXT, \
         d INT GENERATED ALWAYS AS (a*abs(b)) VIRTUAL, \
         e TEXT GENERATED ALWAYS AS (substr(c,b,b+1)) STORED)",
    );
    last(&mut session, "INSERT INTO t1 VALUES (1, 2, 'hello')");
    last(
        &mut session,
        "INSERT INTO t1 (a, b, c) VALUES (2, 1, 'world')",
    );
    assert_eq!(
        last(&mut session, "SELECT a, d, e FROM t1 ORDER BY a"),
        "a|d|e\n1|2|ell\n2|2|wo\nSELECT 2"
    );
    let error = fails(&mut session, "INSERT INTO t1 (a, d) VALUES (3, 4)");
    assert_eq!(error.message(), "cannot INSERT into generated column \"d\"");
    let error = fails(&mut session, "UPDATE t1 SET e = 'x'");
    assert_eq!(error.message(), "cannot UPDATE generated column \"e\"");
    assert_eq!(
        last(&mut session, "PRAGMA table_xinfo(t1)"),
        "cid|name|type|notnull|dflt_value|pk|hidden\n\
         0|a|INTEGER|0|NULL|1|0\n1|b|INT|0|NULL|0|0\n2|c|TEXT|0|NULL|0|0\n\
         3|d|INT|0|NULL|0|2\n4|e|TEXT|0|NULL|0|3\nSELECT 5"
    );
    assert_eq!(
        last(&mut session, "PRAGMA table_info(t1)"),
        "cid|name|type|notnull|dflt_value|pk\n\
         0|a|INTEGER|0|NULL|1\n1|b|INT|0|NULL|0\n2|c|TEXT|0|NULL|0\nSELECT 3"
    );
    let error = fails(
        &mut session,
        "CREATE TABLE t2 (a INT, b INT GENERATED ALWAYS AS (a) PRIMARY KEY)",
    );
    assert_eq!(
        error.message(),
        "generated columns cannot be part of the PRIMARY KEY"
    );
    let error = fails(
        &mut session,
        "ALTER TABLE t1 ADD COLUMN f INT AS (a + 1) STORED",
    );
    assert_eq!(error.message(), "Cannot add a STORED column");
    last(&mut session, "ALTER TABLE t1 ADD COLUMN f INT AS (a + 1)");
    assert_eq!(
        last(&mut session, "SELECT f FROM t1 ORDER BY a"),
        "f\n2\n3\nSELECT 2"
    );
}

#[test]
fn sql_server_computed_columns_are_left_out_of_inserts_and_refuse_writes_with_271() {
    let store = MemoryStore::default();
    let mut session = Session::with_dialect(&store, Dialect::SqlServer);
    last(
        &mut session,
        "CREATE TABLE products (qty int, price int, total AS (qty * price) PERSISTED, \
         doubled AS qty * 2)",
    );
    last(&mut session, "INSERT INTO products VALUES (25, 2)");
    last(
        &mut session,
        "INSERT INTO products (qty, price) VALUES (10, 3)",
    );
    assert_eq!(
        last(
            &mut session,
            "SELECT qty, total, doubled FROM products ORDER BY qty"
        ),
        "qty|total|doubled\n10|30|20\n25|50|50\nSELECT 2"
    );
    let error = fails(
        &mut session,
        "INSERT INTO products (qty, price, total) VALUES (1, 1, 1)",
    );
    assert_eq!(error.vendor_code(), Some(271));
    assert_eq!(
        error.message(),
        "The column \"total\" cannot be modified because it is either a computed column or is the result of a UNION operator."
    );
    assert_eq!(
        fails(&mut session, "UPDATE products SET doubled = 1").vendor_code(),
        Some(271)
    );
    assert_eq!(
        last(
            &mut session,
            "SELECT name, is_computed FROM sys.columns \
             WHERE object_id = OBJECT_ID('products') ORDER BY column_id"
        ),
        "name|is_computed\nqty|f\nprice|f\ntotal|t\ndoubled|t\nSELECT 4"
    );
    let error = fails(
        &mut session,
        "CREATE TABLE twice (a int, b AS (a + 1), c AS (b + 1))",
    );
    assert_eq!(error.vendor_code(), Some(1759));
}

#[test]
fn sql_server_refuses_a_computed_column_whose_value_changes_between_reads() {
    let store = MemoryStore::default();
    let mut session = Session::with_dialect(&store, Dialect::SqlServer);
    for create in [
        "CREATE TABLE people (dob date, age AS DATEDIFF(year, dob, GETDATE()))",
        "CREATE TABLE tokens (id int, token AS NEWID())",
    ] {
        let error = fails(&mut session, create);
        assert_eq!(error.state().code(), "0A000", "{create}");
        assert!(
            error.message().contains("changes between reads"),
            "{create}"
        );
    }
    let error = fails(
        &mut session,
        "CREATE TABLE stamped (id int, stamp AS GETDATE() PERSISTED)",
    );
    assert_eq!(error.vendor_code(), Some(4936));
    last(&mut session, "CREATE TABLE plain (id int)");
    let error = fails(&mut session, "ALTER TABLE plain ADD stamp AS SYSDATETIME()");
    assert_eq!(error.state().code(), "0A000");
}

#[test]
fn oracle_virtual_columns_refuse_writes_with_ora_54013_and_show_in_user_tab_cols() {
    let store = MemoryStore::default();
    let mut session = Session::with_dialect(&store, Dialect::Oracle);
    last(
        &mut session,
        "CREATE TABLE emp (salary NUMBER, bonus NUMBER, \
         total NUMBER GENERATED ALWAYS AS (salary + bonus) VIRTUAL, \
         doubled AS (salary * 2))",
    );
    last(
        &mut session,
        "INSERT INTO emp (salary, bonus) VALUES (100, 10)",
    );
    assert_eq!(
        last(&mut session, "SELECT total, doubled FROM emp"),
        "TOTAL|DOUBLED\n110|200\nSELECT 1"
    );
    let error = fails(
        &mut session,
        "INSERT INTO emp (salary, bonus, total) VALUES (1, 1, 1)",
    );
    assert_eq!(error.vendor_code(), Some(54013));
    assert_eq!(
        fails(&mut session, "UPDATE emp SET total = 1").vendor_code(),
        Some(54017)
    );
    assert_eq!(
        last(
            &mut session,
            "SELECT column_name, virtual_column FROM user_tab_cols \
             WHERE table_name = 'EMP' ORDER BY column_id"
        ),
        "COLUMN_NAME|VIRTUAL_COLUMN\nSALARY|NO\nBONUS|NO\nTOTAL|YES\nDOUBLED|YES\nSELECT 4"
    );
    let error = fails(&mut session, "ALTER TABLE emp DROP COLUMN bonus");
    assert_eq!(error.vendor_code(), Some(54031));
}

