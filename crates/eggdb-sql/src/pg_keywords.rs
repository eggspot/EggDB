pub(crate) fn category(word: &str) -> Option<KeywordCategory> {
    KEYWORDS
        .binary_search_by(|(keyword, _)| keyword.as_bytes().cmp(word.as_bytes()))
        .ok()
        .map(|index| KEYWORDS[index].1)
}

pub(crate) fn quote_ident(name: &str) -> String {
    let plain = name
        .bytes()
        .next()
        .is_some_and(|first| first.is_ascii_lowercase() || first == b'_')
        && name
            .bytes()
            .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'_')
        && category(name).is_none_or(|found| found == KeywordCategory::Unreserved);
    if plain {
        return name.to_owned();
    }
    let mut quoted = String::with_capacity(name.len() + 2);
    quoted.push('"');
    for character in name.chars() {
        if character == '"' {
            quoted.push('"');
        }
        quoted.push(character);
    }
    quoted.push('"');
    quoted
}

#[cfg(test)]
mod tests {
    use super::{KEYWORDS, KeywordCategory, category, quote_ident};

    #[test]
    fn key_words_are_sorted_for_the_binary_search() {
        assert!(
            KEYWORDS
                .windows(2)
                .all(|pair| pair[0].0.as_bytes() < pair[1].0.as_bytes())
        );
        assert_eq!(category("select"), Some(KeywordCategory::Reserved));
        assert_eq!(category("left"), Some(KeywordCategory::TypeOrFunctionName));
        assert_eq!(category("int"), Some(KeywordCategory::ColumnName));
        assert_eq!(category("name"), Some(KeywordCategory::Unreserved));
        assert_eq!(category("text"), Some(KeywordCategory::Unreserved));
        assert_eq!(category("people"), None);
    }

    #[test]
    fn quote_ident_quotes_what_postgresql_quotes() {
        let cases = [
            ("abc", "abc"),
            ("Abc", "\"Abc\""),
            ("a b", "\"a b\""),
            ("between", "\"between\""),
            ("left", "\"left\""),
            ("int", "\"int\""),
            ("name", "name"),
            ("a\"b", "\"a\"\"b\""),
            ("", "\"\""),
            ("_x1", "_x1"),
            ("1x", "\"1x\""),
            ("select", "\"select\""),
            ("text", "text"),
            ("\u{e9}", "\"\u{e9}\""),
        ];
        for (name, quoted) in cases {
            assert_eq!(quote_ident(name), quoted, "{name}");
        }
    }
}
